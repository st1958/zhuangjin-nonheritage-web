/* 互动留言页交互脚本：留言校验、云端读写、留言墙渲染、长留言折叠。 */
(function () {


  // 3 留言：字数统计 + 校验 + 云端/本地保存 + 渲染留言墙
  var form = document.getElementById('msgForm');
  if (!form) return;

  var wall = document.getElementById('msgWall') || document.querySelector('.wall');
  var tip = form.querySelector('.tip');
  var counter = document.getElementById('msgCounter');
  var countBox = document.getElementById('msgCount');
  var inputName = form.elements.name;
  var inputText = form.elements.text;
  var submitBtn = form.querySelector('.btn');

  var KEY = 'jinyun_messages';       // 本机留言列表
  var NICK_KEY = 'jinyun_nickname';  // 上次用的昵称
  var LIMIT = 80;                    // 正文最多 80 字
  var NAME_LIMIT = 16;               // 昵称最多 16 字
  var MAX_KEEP = 40;                 // 本地最多留 40 条

  // 是否启用云端：两个值都填了才算开启
  var CFG = window.CLOUD_CONFIG || {};
  var CLOUD_ON = !!(CFG.url && CFG.key);
  var BASE = String(CFG.url || '').replace(/\/$/, '');

  var memory = [];   // 浏览器禁用本地存储或云端失败时的兜底

  // 按“字”计数：一个汉字、一个字母、一个表情都算 1 个字
  function len(s) { return Array.from(s).length; }

  /* ---------- 本机存储 ---------- */
  function loadLocal() {
    try {
      var raw = localStorage.getItem(KEY);
      return raw ? JSON.parse(raw) : [];
    } catch (e) { return memory.slice(); }
  }

  function saveLocal(list) {
    var cut = list.slice(-MAX_KEEP);
    memory = cut.slice();
    try { localStorage.setItem(KEY, JSON.stringify(cut)); } catch (e) {}
  }

  /* ---------- 云端接口（Supabase REST） ---------- */
  function api(path, method, body) {
    var opt = { method: method || 'GET' };
    opt.headers = {
      'apikey': CFG.key,
      'Authorization': 'Bearer ' + CFG.key,
      'Content-Type': 'application/json'
    };
    if (body) {
      opt.body = JSON.stringify(body);
      opt.headers['Prefer'] = 'return=representation';   // 提交后把新数据返回
    }
    return fetch(BASE + '/rest/v1/' + path, opt);
  }

  function loadCloud() {
    return api('messages?select=id,name,text,created_at&order=created_at.asc&limit=' + MAX_KEEP)
      .then(function (r) {
        if (!r.ok) throw new Error('读取失败 ' + r.status);
        return r.json();
      })
      .then(function (rows) {
        return rows.map(function (x) {
          return { id: x.id, name: x.name, text: x.text, time: x.created_at };
        });
      });
  }

  function addCloud(item) {
    return api('messages', 'POST', [{ name: item.name, text: item.text }])
      .then(function (r) {
        if (!r.ok) throw new Error('提交失败 ' + r.status);
        return r.json();
      })
      .then(function (rows) {
        var x = rows && rows[0];
        return { id: x ? x.id : item.id, name: item.name, text: item.text, time: x ? x.created_at : item.time };
      });
  }

  function delCloud(id) {
    return api('messages?id=eq.' + encodeURIComponent(id), 'DELETE')
      .then(function (r) { if (!r.ok) throw new Error('删除失败 ' + r.status); return true; });
  }

  /* ---------- 渲染 ---------- */
  function pad(n) { return n < 10 ? '0' + n : '' + n; }

  function stamp(d) {
    return d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate()) +
      ' ' + pad(d.getHours()) + ':' + pad(d.getMinutes());
  }

  // 时间显示：刚刚 / 几分钟前 / 几小时前 / 几月几日
  function fmtTime(t) {
    if (!t) return '';
    var d = new Date(t);
    if (isNaN(d.getTime())) d = new Date(String(t).replace(/-/g, '/'));
    if (isNaN(d.getTime())) return '';
    var diff = Math.floor((new Date() - d) / 60000);
    if (diff < 1) return '刚刚';
    if (diff < 60) return diff + ' 分钟前';
    if (diff < 1440) return Math.floor(diff / 60) + ' 小时前';
    return (d.getMonth() + 1) + ' 月 ' + d.getDate() + ' 日';
  }

  // 生成一条留言节点，全部用 textContent 写入，避免用户输入当成 HTML 执行
  function build(item) {
    var el = document.createElement('div');
    el.className = 'note';
    if (item.id) el.dataset.id = item.id;

    var ava = document.createElement('div');
    ava.className = 'ava';
    ava.textContent = (item.name || '访').charAt(0);

    var main = document.createElement('div');
    var b = document.createElement('b');
    b.textContent = item.name;
    if (item.time) {
      var time = document.createElement('time');
      time.textContent = fmtTime(item.time);
      time.title = item.time;
      b.appendChild(time);
    }
    var txt = document.createElement('div');
    txt.className = 'txt';
    txt.textContent = item.text;
    main.appendChild(b);
    main.appendChild(txt);

    el.appendChild(ava);
    el.appendChild(main);

    // 页面上不放删除入口：留言墙对所有人开放，清理留言统一在 Supabase 后台做。
    // 需要恢复删除按钮时，把 ALLOW_DELETE 改成 true 即可。
    var ALLOW_DELETE = false;
    if (ALLOW_DELETE && item.id) {
      var del = document.createElement('button');
      del.type = 'button';
      del.className = 'del';
      del.title = '删除这条留言';
      del.textContent = '删除';
      el.appendChild(del);
    }
    return el;
  }

  function toggleEmpty() {
    var n = wall.querySelectorAll('.note').length;
    var empty = wall.querySelector('.empty');
    if (!n && !empty) {
      empty = document.createElement('div');
      empty.className = 'empty';
      empty.textContent = '还没有留言，来写第一条吧。';
      wall.appendChild(empty);
    } else if (n && empty) {
      empty.remove();
    }
  }

  function refreshCount() {
    var n = wall.querySelectorAll('.note').length;
    if (countBox) countBox.textContent = n + ' 条';
    toggleEmpty();
  }

  // 按顺序插到最前面：传进来的列表是从旧到新，结果最新的在最上面
  function renderList(list) {
    list.forEach(function (m) { wall.insertBefore(build(m), wall.firstChild); });
    refreshCount();
  }

  function fail(msg, field) {
    tip.classList.remove('ok');
    tip.textContent = msg;
    if (field) field.focus();
  }

  function updateCounter() {
    var n = len(inputText.value);
    if (counter) {
      counter.textContent = n + ' / ' + LIMIT;
      counter.classList.toggle('over', n > LIMIT);
    }
  }

  /* ---------- 初始化 ---------- */
  function initLocal() {
    renderList(loadLocal());
  }

  function initCloud() {
    loadCloud()
      .then(function (list) { renderList(list); })
      .catch(function () {
        // 云端连不上：安静地退回本机，页面上不留报错
        renderList(loadLocal());
      });
  }

  if (CLOUD_ON) initCloud(); else initLocal();
  updateCounter();

  try {
    var nick = localStorage.getItem(NICK_KEY);
    if (nick && !inputName.value) inputName.value = nick;
  } catch (e) {}

  inputText.addEventListener('input', function () { updateCounter(); tip.textContent = ''; });
  inputName.addEventListener('input', function () { tip.textContent = ''; });

  /* ---------- 提交 ---------- */
  function afterSubmit(item, isCloud) {
    // 云端失败时条目已存本机，用本机 id 保证还能删
    wall.insertBefore(build(item), wall.firstChild);
    refreshCount();
    inputText.value = '';      // 只清正文，昵称保留
    updateCounter();
    inputText.focus();

    tip.classList.add('ok');
    tip.textContent = isCloud ? '已提交，其他人也能看到了。' : '已提交，联网后会自动同步给其他人。';

    submitBtn.disabled = true;
    setTimeout(function () { submitBtn.disabled = false; }, 800);
  }

  form.addEventListener('submit', function (e) {
    e.preventDefault();   // 阻止浏览器默认刷新页面
    var name = inputName.value.trim();
    var text = inputText.value.trim();

    if (!name) { fail('请先填一个昵称', inputName); return; }
    if (len(name) > NAME_LIMIT) { fail('昵称请控制在 16 字以内', inputName); return; }
    if (!text) { fail('留言内容不能为空', inputText); return; }
    if (len(text) > LIMIT) { fail('留言请控制在 80 字以内，现在 ' + len(text) + ' 字', inputText); return; }

    try { localStorage.setItem(NICK_KEY, name); } catch (e) {}

    var item = {
      id: '',
      name: name,
      text: text,
      time: stamp(new Date())
    };

    if (CLOUD_ON) {
      submitBtn.disabled = true;
      addCloud(item)
        .then(function (saved) { afterSubmit(saved, true); })
        .catch(function () {
          item.id = 'local-' + Date.now();
          var list = loadLocal(); list.push(item); saveLocal(list);
          afterSubmit(item, false);
          tip.textContent = '已先记在这台设备，联网后自动补传。';
        })
        .then(function () {
          setTimeout(function () { submitBtn.disabled = false; }, 800);
        });
    } else {
      item.id = 'local-' + Date.now();
      var list = loadLocal(); list.push(item); saveLocal(list);
      afterSubmit(item, false);
    }
  });

  /* ---------- 删除（事件委托，点哪条删哪条） ---------- */
  wall.addEventListener('click', function (e) {
    var btn = e.target.closest ? e.target.closest('.del') : null;
    if (!btn) return;
    var note = btn.closest('.note');
    if (!note) return;
    if (!window.confirm('确定删除这条留言吗？')) return;

    var id = note.dataset.id || '';

    function removeLocal() {
      saveLocal(loadLocal().filter(function (m) { return String(m.id) !== id; }));
      note.remove();
      refreshCount();
    }

    if (!id) { note.remove(); refreshCount(); return; }

    if (CLOUD_ON && !/^local-/.test(id)) {
      delCloud(id).then(removeLocal).catch(function () {
        tip.classList.remove('ok');
        tip.textContent = '删除失败，请检查网络后重试。';
      });
    } else {
      removeLocal();
    }
  });
})();

/* ---------- 15 长留言：超过三行先折起来 ---------- */
(function () {
  var wall = document.getElementById('msgWall') || document.querySelector('.wall');
  if (!wall) return;
  function tune() {
    var notes = wall.querySelectorAll('.note');
    for (var i = 0; i < notes.length; i++) {
      var n = notes[i], t = n.querySelector('.txt');
      if (!t || n.getAttribute('data-fold')) continue;
      n.setAttribute('data-fold', '1');
      if (t.textContent.replace(/\s/g, '').length < 46) continue;
      t.className = 'txt clamp';
      var b = document.createElement('button');
      b.type = 'button';
      b.className = 'more';
      b.textContent = '展开全文';
      (function (txt, btn) {
        btn.addEventListener('click', function () {
          var clamped = txt.className.indexOf('clamp') >= 0;
          txt.className = clamped ? 'txt' : 'txt clamp';
          btn.textContent = clamped ? '收起' : '展开全文';
        });
      })(t, b);
      t.parentNode.appendChild(b);
    }
  }
  tune();
  if (window.MutationObserver) {
    new MutationObserver(function () { tune(); }).observe(wall, { childList: true });
  }
})();

/* ---------- 19 留言时间改成“刚刚 / 几分钟前”，一分钟刷一次 ---------- */
(function () {
  var wall = document.querySelector('#msgWall');
  if (!wall) return;

  function pad(n) { return n < 10 ? '0' + n : '' + n; }
  function rel(raw) {
    var d = new Date(raw);
    if (isNaN(d.getTime())) return null;
    var s = (Date.now() - d.getTime()) / 1000;
    if (s < 60) return '刚刚';
    if (s < 3600) return Math.floor(s / 60) + ' 分钟前';
    if (s < 86400) return Math.floor(s / 3600) + ' 小时前';
    if (s < 604800) return Math.floor(s / 86400) + ' 天前';
    return d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate());
  }
  function refresh() {
    var ts = wall.querySelectorAll('time');
    for (var i = 0; i < ts.length; i++) {
      var raw = ts[i].getAttribute('title') || ts[i].textContent;
      var r = rel(raw);
      // 值没变就不写：写 textContent 会替换文本节点，本身又会触发下面的观察器，形成死循环
      if (r && ts[i].textContent !== r) ts[i].textContent = r;
      if (ts[i].getAttribute('title') !== raw) ts[i].setAttribute('title', raw);
    }
  }
  refresh();
  new MutationObserver(refresh).observe(wall, { childList: true, subtree: true });
  setInterval(refresh, 60000);
})();

/* ---------- 网络不稳时的兜底：请求限时、留言自动补传 ---------- */
(function () {
  var CFG = window.CLOUD_CONFIG || {};
  if (!CFG.url || !CFG.key) return;
  var BASE = String(CFG.url).replace(/\/$/, '');
  var HOST = BASE.replace(/^https?:\/\//i, '').split('/')[0];
  var KEY_LOCAL = 'jinyun_messages';
  var KEEP = 40;

  // 1 云端请求最多等 8 秒，超时立刻按“没连上”处理，不在手机上一直转圈
  var rawFetch = window.fetch;
  window.fetch = function (input, init) {
    var url = typeof input === 'string' ? input : (input && input.url) || '';
    if (url.indexOf(HOST) < 0 || !window.AbortController) {
      return rawFetch.apply(window, arguments);
    }
    var ctrl = new window.AbortController();
    var opt = {};
    var k;
    if (init) { for (k in init) { if (Object.prototype.hasOwnProperty.call(init, k)) opt[k] = init[k]; } }
    opt.signal = ctrl.signal;
    var timer = setTimeout(function () { ctrl.abort(); }, 8000);
    return rawFetch.call(window, input, opt).then(
      function (r) { clearTimeout(timer); return r; },
      function (e) { clearTimeout(timer); throw e; }
    );
  };

  // 2 本机列表里 id 以 local- 开头的，就是还没传上云的那几条
  function readLocal() {
    try { return JSON.parse(localStorage.getItem(KEY_LOCAL) || '[]') || []; }
    catch (e) { return []; }
  }

  function writeLocal(list) {
    try { localStorage.setItem(KEY_LOCAL, JSON.stringify(list.slice(-KEEP))); } catch (e) {}
  }

  function pending() {
    var out = [], list = readLocal(), i;
    for (i = 0; i < list.length; i++) {
      if (String((list[i] && list[i].id) || '').indexOf('local-') === 0) out.push(list[i]);
    }
    return out;
  }

  var syncing = false;

  function syncPending() {
    if (syncing) return;
    var list = pending();
    if (!list.length) return;
    syncing = true;
    var i = 0;

    (function step() {
      if (i >= list.length) { syncing = false; return; }
      var m = list[i++];
      window.fetch(BASE + '/rest/v1/messages', {
        method: 'POST',
        headers: {
          'apikey': CFG.key,
          'Authorization': 'Bearer ' + CFG.key,
          'Content-Type': 'application/json'
        },
        body: JSON.stringify([{ name: m.name, text: m.text }])
      }).then(function (r) {
        if (r.ok) {
          // 传上去了就把本机这份删掉，下次打开页面读云端不会重复
          var id = String(m.id);
          writeLocal(readLocal().filter(function (x) { return String(x.id) !== id; }));
        }
        setTimeout(step, 300);
      }, function () {
        setTimeout(step, 2600);   // 这条没成，先跳过，下一轮再说
      });
    })();
  }

  // 3 提交那一下最容易赶上网络抖动：2.5 秒、9 秒各补传一次
  var form = document.getElementById('msgForm');
  if (form) {
    form.addEventListener('submit', function () {
      setTimeout(syncPending, 2500);
      setTimeout(syncPending, 9000);
    });
  }

  // 4 墙上已经有留言时，别让“正在读取云端留言”一直挂着
  setTimeout(function () {
    var ld = document.querySelector('.wall-loading');
    var wall = document.getElementById('msgWall') || document.querySelector('.wall');
    if (ld && wall && wall.querySelectorAll('.note').length) ld.parentNode.removeChild(ld);
  }, 1200);

  // 5 三个时机补传：页面打开、切回前台、网络恢复；再每 60 秒兜一次
  setTimeout(syncPending, 1500);
  window.addEventListener('online', syncPending);
  document.addEventListener('visibilitychange', function () {
    if (!document.hidden) syncPending();
  });
  setInterval(syncPending, 60000);
})();

/* ===== 补充：输入时让输入框避开键盘、并减轻滚动重排（第九组追加） ===== */
(function () {
  var form = document.getElementById('msgForm');
  if (!form) return;
  var prog = null;

  function isField(el) {
    return el && (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA');
  }

  // 输入期间把进度条移出渲染树：它每次滚动都在改宽度，容易和键盘动画抢帧
  document.addEventListener('focusin', function (e) {
    if (!isField(e.target)) return;
    var p = document.querySelector('.prog');
    if (p) { prog = p; p.style.display = 'none'; }
    // 键盘弹起有动画，等它落位再把输入框挪到可视区中间
    setTimeout(function () {
      try { e.target.scrollIntoView({ block: 'center' }); } catch (err) {}
    }, 320);
  }, true);

  document.addEventListener('focusout', function (e) {
    if (!isField(e.target)) return;
    if (prog) { prog.style.display = ''; prog = null; }
  }, true);

  // 键盘把可视区压小后，再对一次位，保证输入框和提交按钮不被挡住
  if (window.visualViewport) {
    window.visualViewport.addEventListener('resize', function () {
      var a = document.activeElement;
      if (!isField(a)) return;
      try { a.scrollIntoView({ block: 'center' }); } catch (err) {}
    });
  }
})();
