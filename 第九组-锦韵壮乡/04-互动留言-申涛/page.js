(function () {
  // 1 汉堡菜单
  var burger = document.querySelector('.burger');
  var links = document.querySelector('.links');
  if (burger && links) {
    burger.addEventListener('click', function () { links.classList.toggle('open'); });
    links.addEventListener('click', function (e) {
      if (e.target.tagName === 'A') links.classList.remove('open');
    });
  }

  // 2 纹样筛选
  var chips = Array.prototype.slice.call(document.querySelectorAll('.chip'));
  var figs = Array.prototype.slice.call(document.querySelectorAll('.gal figure'));
  if (chips.length && figs.length) {
    chips.forEach(function (c) {
      c.addEventListener('click', function () {
        chips.forEach(function (x) { x.classList.toggle('on', x === c); });
        var key = c.dataset.cat || '全部';
        figs.forEach(function (f) {
          var cats = (f.dataset.cat || '').split(',');
          f.hidden = !(key === '全部' || cats.indexOf(key) > -1);
        });
      });
    });
  }

  // 3 留言：字数统计 + 校验 + 云端/本地保存 + 渲染留言墙
  var form = document.getElementById('msgForm');
  if (!form) return;

  var wall = document.getElementById('msgWall') || document.querySelector('.wall');
  var tip = form.querySelector('.tip');
  var counter = document.getElementById('msgCounter');
  var countBox = document.getElementById('msgCount');
  var inputName = form.elements.name;
  var inputText = form.elements.text;
  var submitBtn = form.querySelector('.btn');

  var KEY = 'jinyun_messages';       // 本机留言列表
  var NICK_KEY = 'jinyun_nickname';  // 上次用的昵称
  var LIMIT = 80;                    // 正文最多 80 字
  var NAME_LIMIT = 16;               // 昵称最多 16 字
  var MAX_KEEP = 40;                 // 本地最多留 40 条

  // 是否启用云端：两个值都填了才算开启
  var CFG = window.CLOUD_CONFIG || {};
  var CLOUD_ON = !!(CFG.url && CFG.key);
  var BASE = String(CFG.url || '').replace(/\/$/, '');

  var memory = [];   // 浏览器禁用本地存储或云端失败时的兜底

  // 按“字”计数：一个汉字、一个字母、一个表情都算 1 个字
  function len(s) { return Array.from(s).length; }

  /* ---------- 本机存储 ---------- */
  function loadLocal() {
    try {
      var raw = localStorage.getItem(KEY);
      return raw ? JSON.parse(raw) : [];
    } catch (e) { return memory.slice(); }
  }

  function saveLocal(list) {
    var cut = list.slice(-MAX_KEEP);
    memory = cut.slice();
    try { localStorage.setItem(KEY, JSON.stringify(cut)); } catch (e) {}
  }

  /* ---------- 云端接口（Supabase REST） ---------- */
  function api(path, method, body) {
    var opt = { method: method || 'GET' };
    opt.headers = {
      'apikey': CFG.key,
      'Authorization': 'Bearer ' + CFG.key,
      'Content-Type': 'application/json'
    };
    if (body) {
      opt.body = JSON.stringify(body);
      opt.headers['Prefer'] = 'return=representation';   // 提交后把新数据返回
    }
    return fetch(BASE + '/rest/v1/' + path, opt);
  }

  function loadCloud() {
    return api('messages?select=id,name,text,created_at&order=created_at.asc&limit=' + MAX_KEEP)
      .then(function (r) {
        if (!r.ok) throw new Error('读取失败 ' + r.status);
        return r.json();
      })
      .then(function (rows) {
        return rows.map(function (x) {
          return { id: x.id, name: x.name, text: x.text, time: x.created_at };
        });
      });
  }

  function addCloud(item) {
    return api('messages', 'POST', [{ name: item.name, text: item.text }])
      .then(function (r) {
        if (!r.ok) throw new Error('提交失败 ' + r.status);
        return r.json();
      })
      .then(function (rows) {
        var x = rows && rows[0];
        return { id: x ? x.id : item.id, name: item.name, text: item.text, time: x ? x.created_at : item.time };
      });
  }

  function delCloud(id) {
    return api('messages?id=eq.' + encodeURIComponent(id), 'DELETE')
      .then(function (r) { if (!r.ok) throw new Error('删除失败 ' + r.status); return true; });
  }

  /* ---------- 渲染 ---------- */
  function pad(n) { return n < 10 ? '0' + n : '' + n; }

  function stamp(d) {
    return d.getFullYear() + '-' + pad(d.getMonth() + 1) + '-' + pad(d.getDate()) +
      ' ' + pad(d.getHours()) + ':' + pad(d.getMinutes());
  }

  // 时间显示：刚刚 / 几分钟前 / 几小时前 / 几月几日
  function fmtTime(t) {
    if (!t) return '';
    var d = new Date(t);
    if (isNaN(d.getTime())) d = new Date(String(t).replace(/-/g, '/'));
    if (isNaN(d.getTime())) return '';
    var diff = Math.floor((new Date() - d) / 60000);
    if (diff < 1) return '刚刚';
    if (diff < 60) return diff + ' 分钟前';
    if (diff < 1440) return Math.floor(diff / 60) + ' 小时前';
    return (d.getMonth() + 1) + ' 月 ' + d.getDate() + ' 日';
  }

  // 生成一条留言节点，全部用 textContent 写入，避免用户输入当成 HTML 执行
  function build(item) {
    var el = document.createElement('div');
    el.className = 'note';
    if (item.id) el.dataset.id = item.id;

    var ava = document.createElement('div');
    ava.className = 'ava';
    ava.textContent = (item.name || '访').charAt(0);

    var main = document.createElement('div');
    var b = document.createElement('b');
    b.textContent = item.name;
    if (item.time) {
      var time = document.createElement('time');
      time.textContent = fmtTime(item.time);
      time.title = item.time;
      b.appendChild(time);
    }
    var txt = document.createElement('div');
    txt.className = 'txt';
    txt.textContent = item.text;
    main.appendChild(b);
    main.appendChild(txt);

    el.appendChild(ava);
    el.appendChild(main);

    // 有 id 的（云端或自己提交的）才显示删除按钮
    if (item.id) {
      var del = document.createElement('button');
      del.type = 'button';
      del.className = 'del';
      del.title = '删除这条留言';
      del.textContent = '删除';
      el.appendChild(del);
    }
    return el;
  }

  function toggleEmpty() {
    var n = wall.querySelectorAll('.note').length;
    var empty = wall.querySelector('.empty');
    if (!n && !empty) {
      empty = document.createElement('div');
      empty.className = 'empty';
      empty.textContent = '还没有留言，来写第一条吧。';
      wall.appendChild(empty);
    } else if (n && empty) {
      empty.remove();
    }
  }

  function refreshCount() {
    var n = wall.querySelectorAll('.note').length;
    if (countBox) countBox.textContent = n + ' 条';
    toggleEmpty();
  }

  // 按顺序插到最前面：传进来的列表是从旧到新，结果最新的在最上面
  function renderList(list) {
    list.forEach(function (m) { wall.insertBefore(build(m), wall.firstChild); });
    refreshCount();
  }

  function fail(msg, field) {
    tip.classList.remove('ok');
    tip.textContent = msg;
    if (field) field.focus();
  }

  function updateCounter() {
    var n = len(inputText.value);
    if (counter) {
      counter.textContent = n + ' / ' + LIMIT;
      counter.classList.toggle('over', n > LIMIT);
    }
  }

  /* ---------- 初始化 ---------- */
  function initLocal() {
    renderList(loadLocal());
  }

  function initCloud() {
    loadCloud()
      .then(function (list) { renderList(list); })
      .catch(function () {
        // 云端连不上：安静地退回本机，页面上不留报错
        renderList(loadLocal());
      });
  }

  if (CLOUD_ON) initCloud(); else initLocal();
  updateCounter();

  try {
    var nick = localStorage.getItem(NICK_KEY);
    if (nick && !inputName.value) inputName.value = nick;
  } catch (e) {}

  inputText.addEventListener('input', function () { updateCounter(); tip.textContent = ''; });
  inputName.addEventListener('input', function () { tip.textContent = ''; });

  /* ---------- 提交 ---------- */
  function afterSubmit(item, isCloud) {
    // 云端失败时条目已存本机，用本机 id 保证还能删
    wall.insertBefore(build(item), wall.firstChild);
    refreshCount();
    inputText.value = '';      // 只清正文，昵称保留
    updateCounter();
    inputText.focus();

    tip.classList.add('ok');
    tip.textContent = isCloud ? '已提交，其他人也能看到了。' : '已提交，目前只保存在这台设备。';

    submitBtn.disabled = true;
    setTimeout(function () { submitBtn.disabled = false; }, 800);
  }

  form.addEventListener('submit', function (e) {
    e.preventDefault();   // 阻止浏览器默认刷新页面
    var name = inputName.value.trim();
    var text = inputText.value.trim();

    if (!name) { fail('请先填一个昵称', inputName); return; }
    if (len(name) > NAME_LIMIT) { fail('昵称请控制在 16 字以内', inputName); return; }
    if (!text) { fail('留言内容不能为空', inputText); return; }
    if (len(text) > LIMIT) { fail('留言请控制在 80 字以内，现在 ' + len(text) + ' 字', inputText); return; }

    try { localStorage.setItem(NICK_KEY, name); } catch (e) {}

    var item = {
      id: '',
      name: name,
      text: text,
      time: stamp(new Date())
    };

    if (CLOUD_ON) {
      submitBtn.disabled = true;
      addCloud(item)
        .then(function (saved) { afterSubmit(saved, true); })
        .catch(function () {
          item.id = 'local-' + Date.now();
          var list = loadLocal(); list.push(item); saveLocal(list);
          afterSubmit(item, false);
          tip.textContent = '网络暂时连不上，这条先存在这台设备。';
        })
        .then(function () {
          setTimeout(function () { submitBtn.disabled = false; }, 800);
        });
    } else {
      item.id = 'local-' + Date.now();
      var list = loadLocal(); list.push(item); saveLocal(list);
      afterSubmit(item, false);
    }
  });

  /* ---------- 删除（事件委托，点哪条删哪条） ---------- */
  wall.addEventListener('click', function (e) {
    var btn = e.target.closest ? e.target.closest('.del') : null;
    if (!btn) return;
    var note = btn.closest('.note');
    if (!note) return;
    if (!window.confirm('确定删除这条留言吗？')) return;

    var id = note.dataset.id || '';

    function removeLocal() {
      saveLocal(loadLocal().filter(function (m) { return String(m.id) !== id; }));
      note.remove();
      refreshCount();
    }

    if (!id) { note.remove(); refreshCount(); return; }

    if (CLOUD_ON && !/^local-/.test(id)) {
      delCloud(id).then(removeLocal).catch(function () {
        tip.classList.remove('ok');
        tip.textContent = '删除失败，请检查网络后重试。';
      });
    } else {
      removeLocal();
    }
  });
})();
